/**
 * Materializes the starter kit for a given BuildConfig. Walks starter-kit/,
 * reads every file into memory, and substitutes kit.config.ts with a generated
 * module whose exports match the BuildConfig.
 *
 * Output is an array of {path, content} pairs ready to be uploaded to a
 * deployment provider. No disk I/O outside reading the kit source.
 */

import { promises as fs } from "node:fs";
import path from "node:path";
import type { BuildConfig } from "./build-config";

const KIT_ROOT = path.join(process.cwd(), "starter-kit");

const EXCLUDE_DIRS = new Set([
  "node_modules", ".next", ".git", ".vercel", "dist", "build",
]);

const EXCLUDE_FILES = new Set([
  ".env", ".env.local", "package-lock.json", ".DS_Store", "tsconfig.tsbuildinfo",
]);

export type KitFile = { path: string; content: string };

/**
 * Renders the BuildConfig into a TypeScript module string. The kit reads from
 * this file at runtime, so the contract matches starter-kit/kit.config.ts.
 */
export function renderKitConfig(config: BuildConfig): string {
  const json = JSON.stringify(config, null, 2);
  return `// Auto-generated by the AOS AI Build compiler. Do not edit.
// Source: lib/ai-build/materialize.ts → renderKitConfig().

import type { KitConfig } from "./kit.config.types";

export const config: KitConfig = ${json};

export type { KitConfig } from "./kit.config.types";
`;
}

const KIT_CONFIG_TYPES = `// Auto-generated alongside kit.config.ts. The runtime shape of the config
// object. The compiler keeps this in sync with lib/ai-build/build-config.ts.

export type KitConfig = {
  brand: { name: string; tagline: string };
  landing: {
    headline: string;
    subhead: string;
    beforeAfter: { before: string; after: string };
    whyNow: string;
    ctaLabel: string;
  };
  workflow: {
    shape: string;
    title: string;
    inputLabel: string;
    inputPlaceholder: string;
    outputLabel: string;
    submitLabel: string;
    systemPrompt: string;
    promptTemplate: string;
  };
  pricing: { price: string; cadence: string; oneLiner: string; ctaLabel: string };
  about: { builtByLine: string };
  meta: {
    opportunityId: string;
    opportunitySlug: string;
    commitmentId: string;
    userId: string;
    createdAt: string;
  };
};
`;

async function walk(dir: string, base: string, out: KitFile[]): Promise<void> {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  for (const e of entries) {
    if (e.isDirectory()) {
      if (EXCLUDE_DIRS.has(e.name)) continue;
      await walk(path.join(dir, e.name), base, out);
      continue;
    }
    if (EXCLUDE_FILES.has(e.name)) continue;
    const abs = path.join(dir, e.name);
    const rel = path.relative(base, abs).split(path.sep).join("/");
    const content = await fs.readFile(abs, "utf-8");
    out.push({ path: rel, content });
  }
}

/**
 * Returns the kit file tree with kit.config.ts replaced and a sibling
 * kit.config.types.ts written alongside it.
 */
export async function materialize(config: BuildConfig): Promise<KitFile[]> {
  const files: KitFile[] = [];
  await walk(KIT_ROOT, KIT_ROOT, files);

  // Strip the dev-only kit.config.ts; replace with generated module.
  const filtered = files.filter((f) => f.path !== "kit.config.ts");
  filtered.push({ path: "kit.config.ts", content: renderKitConfig(config) });
  filtered.push({ path: "kit.config.types.ts", content: KIT_CONFIG_TYPES });

  // Strip references to KitConfig from the dev kit.config.ts's import shape —
  // the new module imports from kit.config.types instead. The kit's existing
  // component imports (`import { config as kit } from "@/kit.config"`) keep
  // working because we preserved the `config` named export.

  return filtered;
}
